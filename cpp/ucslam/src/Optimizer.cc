// The keys this file and the depth-prior map points use. Same names as Settings::readUcslam.
int ReadUcslamKeys(cv::FileStorage& fs, Settings::Ucslam& u)
{
    int n = 0;
    cv::FileNode node;
    node = fs["UCSLAM.UseDepthFactor"];      if(!node.empty()) { u.useDepthFactor = (int)node; n++; }
    node = fs["UCSLAM.Sigma0"];              if(!node.empty()) { u.sigma0 = (float)node; n++; }
    node = fs["UCSLAM.SigmaRW"];             if(!node.empty()) { u.sigmaRW = (float)node; n++; }
    node = fs["UCSLAM.ESSDeflation"];        if(!node.empty()) { u.essDeflation = (int)node; n++; }
    node = fs["UCSLAM.NeffOverN"];           if(!node.empty()) { u.neffOverN = (float)node; n++; }
    node = fs["UCSLAM.MaxDepthPriorPoints"]; if(!node.empty()) { u.maxDepthPriorPoints = (int)node; n++; }
    node = fs["UCSLAM.SigmaMerge"];          if(!node.empty()) { u.sigmaMerge = (float)node; n++; }
    node = fs["UCSLAM.PriorNet"];            if(!node.empty()) { u.priorNet = (int)node; n++; }
    node = fs["UCSLAM.Diag"];                if(!node.empty()) { u.diag = (int)node; n++; }
    node = fs["UCSLAM.DepthEdgeMinObs"];     if(!node.empty()) { u.depthEdgeMinObs = (int)node; n++; }
    node = fs["UCSLAM.DepthEdgesFixedKFs"];  if(!node.empty()) { u.depthEdgesFixedKFs = (int)node; n++; }
    node = fs["UCSLAM.ChainFixedBoundary"];  if(!node.empty()) { u.chainFixedBoundary = (int)node; n++; }
    node = fs["UCSLAM.ImuInitHandoff"];      if(!node.empty()) { u.imuInitHandoff = (int)node; n++; }
    node = fs["UCSLAM.LogScaleFixed"];       if(!node.empty()) { u.logScaleFixed = (int)node; n++; }
    node = fs["UCSLAM.DepthGateMode"];       if(!node.empty()) { u.depthGateMode = (int)node; n++; }
    node = fs["UCSLAM.DepthEdgesStereoPoints"]; if(!node.empty()) { u.depthEdgesStereoPoints = (int)node; n++; }
    node = fs["UCSLAM.LogScaleSeed"];        if(!node.empty()) { u.logScaleSeed = (int)node; n++; }
    node = fs["UCSLAM.DepthEdgesStereoObs"]; if(!node.empty()) { u.depthEdgesStereoObs = (int)node; n++; }
    node = fs["UCSLAM.DiagLbaDelayMs"];      if(!node.empty()) { u.diagLbaDelayMs = (int)node; n++; }
    // Attempt 08. On this path Settings does not check the subsample's needs, so EnableDepthSubsample does.
    node = fs["UCSLAM.DepthEdgeGateAtAdd"];  if(!node.empty()) { u.depthEdgeGateAtAdd = (int)node; n++; }
    node = fs["UCSLAM.LbaMargDiagOnly"];     if(!node.empty()) { u.lbaMargDiagOnly = (int)node; n++; }
    node = fs["UCSLAM.DepthEdgeSubsampleEps"]; if(!node.empty()) { u.depthEdgeSubsampleEps = (float)node; n++; }
    node = fs["UCSLAM.DiagMargCheck"];       if(!node.empty()) { u.diagMargCheck = (int)node; n++; }
    node = fs["UCSLAM.DiagSubsampleCheck"];  if(!node.empty()) { u.diagSubsampleCheck = (int)node; n++; }
    return n;
}

// Fallback while System does not register the block: the settings YAML is an argument of this
// process, so read the UCSLAM.* keys from it. Linux only, through /proc/self/cmdline.
void LoadUcslamFromCommandLine()
{
    std::ifstream f("/proc/self/cmdline", std::ios::binary);
    if(!f)
    {
        cout << "[UCSLAM] optimizer: no registered UCSLAM.* block and no /proc/self/cmdline, the keys keep their stock defaults" << endl;
        return;
    }
    const std::string all((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
    size_t pos = 0;
    while(pos < all.size())
    {
        size_t end = all.find('\0', pos);
        if(end == std::string::npos)
            end = all.size();
        const std::string arg = all.substr(pos, end - pos);
        pos = end + 1;
        const bool bYaml = arg.size() > 5 &&
            (arg.compare(arg.size() - 5, 5, ".yaml") == 0 || arg.compare(arg.size() - 4, 4, ".yml") == 0);
        if(!bYaml)
            continue;
        cv::FileStorage fs(arg, cv::FileStorage::READ);
        if(!fs.isOpened())
            continue;
        Settings::Ucslam u;
        const int n = ReadUcslamKeys(fs, u);
        if(n == 0)
            continue;
        sUcslam = u;
        cout << "[UCSLAM] optimizer: System did not register the UCSLAM.* block, read " << n << " keys from " << arg
             << ": UseDepthFactor=" << u.useDepthFactor << " Sigma0=" << u.sigma0 << " SigmaRW=" << u.sigmaRW
             << " ESSDeflation=" << u.essDeflation << " NeffOverN=" << u.neffOverN
             << " MaxDepthPriorPoints=" << u.maxDepthPriorPoints << " SigmaMerge=" << u.sigmaMerge << endl;
        return;
    }
    cout << "[UCSLAM] optimizer: System did not register the UCSLAM.* block and no settings file on the command line holds UCSLAM.* keys, the depth factor stays off" << endl;
}

// Stored marginal variance of a keyframe's a_k. A keyframe the BA has not estimated yet
// (mLogScaleVar == 0) carries the absolute prior variance when it is the head, else sigma_0^2.
double UcslamStoredVar(KeyFrame* pKF, const Settings::Ucslam& u)
{
    if(pKF->mLogScaleVar > 0.0)
        return pKF->mLogScaleVar;
    if(pKF->mbLogScalePrior && pKF->mLogScalePriorVar > 0.0)
        return pKF->mLogScalePriorVar;
    return (double)u.sigma0 * (double)u.sigma0;
}

Eigen::Matrix<double,1,1> Info1(double w)
{
    Eigen::Matrix<double,1,1> I;
    I(0,0) = w;
    return I;
}

// UC-SLAM (attempt 08, review R-A): keyframes that observe a point inside the window of the local BA of
// keyframe baKF (marked local or fixed for it, not bad, in pMap), the keyframes that give the point its
// visual edges there. The subsample exempts a point with fewer than 3 of them.
int UcslamWindowObservers(const map<KeyFrame*,tuple<int,int>>& observations, unsigned long baKF, Map* pMap)
{
    int n = 0;
    for(map<KeyFrame*,tuple<int,int>>::const_iterator mit = observations.begin(); mit != observations.end(); ++mit)
    {
        KeyFrame* pKFi = mit->first;
        if((pKFi->mnBALocalForKF == baKF || pKFi->mnBAFixedForKF == baKF) && !pKFi->isBad() && pKFi->GetMap() == pMap)
            n++;
    }
    return n;
}

/*
 * The log-scale chain of one local BA window: its nodes, chain edges, priors and depth edges,
 * the outlier gate, the marginal variances and the write back. One instance per call of
 * LocalInertialBA or LocalBundleAdjustment.
 *
 * Chain edge mPrevKF -> k: information from Map::LogScaleChainTerms::segInfo when a cull stored a
 * merged segment there, else 1 / (sigma_rw^2 dt). A fixed end point holds a_k at its stored value,
 * so its stored marginal variance is added to the segment variance. That is how the window sees
 * the information of everything before it, and how the absolute prior reaches the window once
 * the head is outside it.
 *
 * Marginal variance: after the last optimization the landmarks are eliminated from the Hessian
 * the block solver built at the solution, the dense pose part is inverted, and Var(a_k) is its
 * diagonal entry (UcslamDensePoseSchur). When that is not available for a node, the chain filter
 * Var = 1 / (1 / (Var_prev + sigma_rw^2 dt) + S_k) is used, with S_k the information of the depth
 * edges inside the Huber quadratic region at the solution. The log line says which was used.
 */
class UcslamChainBuilder
{
public:
    // Huber delta of the depth edges, the square root of the chi-square 95 percent quantile with
    // one degree of freedom, and the gate on the squared whitened residual.
    static const double kHuberDepth;
    static const double kChi2Depth;

    UcslamChainBuilder(const Settings::Ucslam& u, g2o::SparseOptimizer& optimizer, unsigned long baseId):
        mu(u), mOptimizer(optimizer), mBaseId(baseId),
        mInfoScale(u.essDeflation ? (double)u.neffOverN : 1.0),
        nChain(0), nPrior(0), nUnary(0), nMerge(0), nDetached(0),
        nGated(0), nMarginal(0), nFilter(0), nDepthFixedKF(0), nDepthDpp(0), nDppPoints(0), nDppSingle(0),
        bDppPoint(false), mbMarginalOk(false), nRecentered(0),
        mPointId(0), mPointObs(0), mbSubsample(false), nGatedAtAdd(0), nCandFree(0), nKeptFree(0),
        nBudgetFree(0), nOverK(0), nActCand(0), nActExempt(0), nActFixed(0), mInfoDev(0.0), mMargCheck(-1.0),
        mMargRcond(-1.0) {}

    // UC-SLAM (attempt 08): candidates that never reached FlushDepthCands are not in the graph.
    ~UcslamChainBuilder()
    {
        for(std::map<unsigned long,DepthCandKF>::iterator it = mCands.begin(); it != mCands.end(); ++it)
            for(size_t i = 0; i < it->second.vEdge.size(); i++)
                delete it->second.vEdge[i];
    }

    // UC-SLAM (UCSLAM.DepthEdgeSubsampleEps, attempt 08): the inertial local BA turns the subsample on for
    // its window. It needs ESS deflation and the gate at add under DepthGateMode 1 (Settings.cc aborts
    // otherwise, this repeats the check for the fallback reader).
    void EnableDepthSubsample()
    {
        mbSubsample = mu.depthEdgeSubsampleEps > 0.f && mu.essDeflation != 0 && mu.depthGateMode == 1 &&
                      mu.depthEdgeGateAtAdd != 0;
    }

    // UC-SLAM (attempt 08): the map point id and the number of keyframes that observe it, for the depth
    // edges that follow. They decide whether an edge is a subsample candidate. The inertial local BA passes
    // the observers inside its window (UcslamWindowObservers), the visual local BA the map-wide count.
    void SetPoint(unsigned long id, int nObs) { mPointId = id; mPointObs = nObs; }

    // One node per keyframe of the window, fixed for a fixed keyframe. A keyframe without a state
    // starts at Optimizer::UcslamSeedLogScale: its predecessor's a_k, the random walk prediction, or
    // with UCSLAM.LogScaleSeed 1 its geometric log-scale.
    VertexLogScale* AddVertex(KeyFrame* pKF, bool bFixed)
    {
        const unsigned long id = mBaseId + pKF->mnId;
        if(mOptimizer.vertex(id))
        {
            cerr << "[UCSLAM] log-scale vertex id " << id << " clashes with an existing vertex, keyframe "
                 << pKF->mnId << " gets no chain node" << endl;
            return NULL;
        }
        // UCSLAM.LogScaleFixed (ablation): every a_k is held at 0.
        const double a = mu.logScaleFixed ? 0.0 : Optimizer::UcslamSeedLogScale(pKF);
        VertexLogScale* v = new VertexLogScale(a);
        v->setId(id);
        v->setFixed(bFixed || mu.logScaleFixed != 0);
        mOptimizer.addVertex(v);
        mVertices[pKF] = v;
        mStoredVar[pKF] = UcslamStoredVar(pKF, mu);
        return v;
    }

    bool HasVertex(KeyFrame* pKF) const { return mVertices.count(pKF) > 0; }

    void AddChainEdges()
    {
        const double sigmaRW2 = (double)mu.sigmaRW * (double)mu.sigmaRW;

        for(std::map<KeyFrame*,VertexLogScale*>::iterator it = mVertices.begin(); it != mVertices.end(); ++it)
        {
            KeyFrame* pKF = it->first;
            VertexLogScale* v = it->second;
            KeyFrame* pPrev = pKF->mPrevKF;
            if(!pPrev)
                continue;
            std::map<KeyFrame*,VertexLogScale*>::iterator itp = mVertices.find(pPrev);
            if(itp == mVertices.end())
                continue;
            VertexLogScale* vp = itp->second;
            if(v->fixed() && vp->fixed())
                continue;
            Map::LogScaleChainTerms terms;
            Map::GetLogScaleChainTerms(pKF, terms);
            double var;
            if(terms.segInfo > 0.0)
                var = 1.0 / terms.segInfo;
            else
            {
                const double dt = std::max(std::fabs(pKF->mTimeStamp - pPrev->mTimeStamp), 1e-6);
                var = std::max(sigmaRW2 * dt, 1e-12);
            }
            if(vp->fixed())
                var += mStoredVar[pPrev];
            if(v->fixed())
                var += mStoredVar[pKF];
            EdgeLogScaleRW* e = new EdgeLogScaleRW();
            e->setVertex(0, vp);
            e->setVertex(1, v);
            e->setInformation(Info1(1.0 / var));
            mOptimizer.addEdge(e);
            nChain++;
        }

        // Relative priors from Atlas merges: a_absorbed - a_surviving ~ N(mean, var).
        const std::vector<Map::LogScaleMergePrior> vMerge = Map::GetLogScaleMergePriors();
        for(size_t i = 0; i < vMerge.size(); i++)
        {
            const Map::LogScaleMergePrior& m = vMerge[i];
            std::map<KeyFrame*,VertexLogScale*>::iterator ia = mVertices.find(m.pAbsorbedHead);
            std::map<KeyFrame*,VertexLogScale*>::iterator is = mVertices.find(m.pSurvivingHead);
            if(ia == mVertices.end() || is == mVertices.end() || !(m.var > 0.0))
                continue;
            if(ia->second->fixed() && is->second->fixed())
                continue;
            EdgeLogScaleRW* e = new EdgeLogScaleRW();
            e->setVertex(0, is->second);
            e->setVertex(1, ia->second);
            e->setMeasurement(m.mean);
            e->setInformation(Info1(1.0 / m.var));
            mOptimizer.addEdge(e);
            nMerge++;
        }

        for(std::map<KeyFrame*,VertexLogScale*>::iterator it = mVertices.begin(); it != mVertices.end(); ++it)
        {
            KeyFrame* pKF = it->first;
            VertexLogScale* v = it->second;
            if(v->fixed())
                continue;
            bool bAnchored = false;
            if(pKF->mbLogScalePrior && pKF->mLogScalePriorVar > 0.0)
            {
                EdgeLogScalePrior* e = new EdgeLogScalePrior(pKF->mLogScalePriorMean);
                e->setVertex(0, v);
                e->setInformation(Info1(1.0 / pKF->mLogScalePriorVar));
                mOptimizer.addEdge(e);
                nPrior++;
                bAnchored = true;
            }
            Map::LogScaleChainTerms terms;
            if(Map::GetLogScaleChainTerms(pKF, terms) && terms.unaryInfo > 0.0)
            {
                EdgeLogScalePrior* e = new EdgeLogScalePrior(terms.unaryB / terms.unaryInfo);
                e->setVertex(0, v);
                e->setInformation(Info1(terms.unaryInfo));
                mOptimizer.addEdge(e);
                nUnary++;
            }
            // The oldest optimizable node of a chain segment whose predecessor is outside the window
            // has no anchor. Hold it at its stored value with its stored variance.
            if(!bAnchored && (!pKF->mPrevKF || !HasVertex(pKF->mPrevKF)))
            {
                EdgeLogScalePrior* e = new EdgeLogScalePrior(v->estimate());
                e->setVertex(0, v);
                e->setInformation(Info1(1.0 / mStoredVar[pKF]));
                mOptimizer.addEdge(e);
                nDetached++;
            }
        }
    }

    // One depth edge for the observation idx of keyframe pKF, when that keyframe has a depth prior there.
    // The information is 1 / sigma_D^2 times N_eff / N under ESS deflation. The Huber kernel and the
    // gate are statements about one measurement, so they act on the undeflated whitened residual:
    // g2o applies both to e^T Omega e, hence the delta and the threshold are scaled by the same factor.
    template<class EdgeT>
    bool AddDepthEdge(KeyFrame* pKF, int idx, g2o::HyperGraph::Vertex* vPoint, g2o::HyperGraph::Vertex* vPose)
    {
        std::map<KeyFrame*,VertexLogScale*>::iterator it = mVertices.find(pKF);
        if(it == mVertices.end() || !vPoint || !vPose || idx < 0)
            return false;
        const bool bFixedKF = static_cast<g2o::OptimizableGraph::Vertex*>(vPose)->fixed();
        if(bFixedKF && !mu.depthEdgesFixedKFs)
            return false;
        DepthPrior& d = mDepth[pKF];
        if(!d.bQueried)
        {
            d.bQueried = true;
            d.bReady = pKF->GetDepthPrior(d.z, d.sigma);
        }
        if(!d.bReady || idx >= (int)d.z.size() || idx >= (int)d.sigma.size())
            return false;
        const float zhat = d.z[idx], sigma = d.sigma[idx];
        if(!(zhat > 0.f) || !(sigma > 0.f))
            return false;

        EdgeT* e = new EdgeT();
        e->setVertex(0, vPoint);
        e->setVertex(1, vPose);
        e->setVertex(2, it->second);
        e->setMeasurement(std::log((double)zhat));
        const double info = mInfoScale / ((double)sigma * (double)sigma);
        e->setInformation(Info1(info));
        // UC-SLAM (UCSLAM.DepthEdgeGateAtAdd, attempt 08, port of attempt 01): under DepthGateMode 1 PreGate tests
        // every edge at the initial estimate, and no estimate moves between here and PreGate. An edge it would
        // reject stays inactive through the one solve, so it is not created.
        if(mu.depthEdgeGateAtAdd && mu.depthGateMode == 1)
        {
            e->computeError();
            if(e->chi2() > kChi2Depth * mInfoScale || !e->isDepthPositive())
            {
                delete e;
                nGated++;
                nGatedAtAdd++;
                return false;
            }
        }
        // UC-SLAM (attempt 08): class 0 free keyframe and a point seen by at least 3 keyframes (a subsample
        // candidate), 1 free keyframe and an exempt point, 2 fixed keyframe.
        const char cls = bFixedKF ? 2 : (UcslamSubsampleEligible(bFixedKF, mPointObs) ? 0 : 1);
        if(mbSubsample && cls == 0)
        {
            // UCSLAM.DepthEdgeSubsampleEps: the candidate waits for FlushDepthCands. The gate at add, which the
            // subsample needs, has just computed its residual at the initial estimate.
            DepthCandKF& ck = mCands[pKF->mnId];
            ck.pKF = pKF;
            const bool bKp = idx < (int)pKF->mvKeysUn.size();
            UcslamDepthCand c;
            c.pointId = mPointId;
            c.u = bKp ? (double)pKF->mvKeysUn[idx].pt.x : (double)pKF->mnMinX;
            c.v = bKp ? (double)pKF->mvKeysUn[idx].pt.y : (double)pKF->mnMinY;
            c.w = info;
            c.r = e->error()(0);
            c.key = UcslamDepthCandKey(mPointId, pKF->mnId);
            ck.vCand.push_back(c);
            ck.vEdge.push_back(e);
            ck.vDpp.push_back(bDppPoint);
            return true;
        }
        if(mbSubsample && cls == 1)
        {
            DepthCandKF& ck = mCands[pKF->mnId];
            ck.pKF = pKF;
            ck.nExempt++;
        }
        g2o::RobustKernelHuber* rk = new g2o::RobustKernelHuber;
        e->setRobustKernel(rk);
        rk->setDelta(kHuberDepth * std::sqrt(mInfoScale));
        AddToGraph(e, pKF, bDppPoint, bFixedKF, cls, 1.0);
        return true;
    }

    // UC-SLAM (UCSLAM.DepthEdgeSubsampleEps, attempt 08): per free keyframe, K of the n candidates enter the
    // graph with the weight c_k, the others are deleted (UcslamSubsampleKeyFrame, UcslamWeightDepthEdge). The
    // inertial local BA calls this after its depth edges and before PreGate. Nothing waits without the key.
    void FlushDepthCands()
    {
        for(std::map<unsigned long,DepthCandKF>::iterator it = mCands.begin(); it != mCands.end(); ++it)
        {
            DepthCandKF& ck = it->second;
            const int n = (int)ck.vCand.size();
            const int K = UcslamSubsampleBudget(n, mInfoScale, (double)mu.depthEdgeSubsampleEps);
            std::vector<char> keep;
            const double c = UcslamSubsampleKeyFrame(ck.vCand, K, (double)ck.pKF->mnMinX, (double)ck.pKF->mnMaxX,
                                                     (double)ck.pKF->mnMinY, (double)ck.pKF->mnMaxY, keep);
            double wCand = 0.0, wKept = 0.0;
            int nKept = 0;
            for(int i = 0; i < n; i++)
            {
                EdgeLogDepthBase* e = ck.vEdge[i];
                wCand += ck.vCand[i].w;
                if(!keep[i])
                {
                    delete e;
                    continue;
                }
                const UcslamDepthWeight dw = UcslamWeightDepthEdge(ck.vCand[i].w, mInfoScale, c);
                e->setInformation(Info1(dw.info));
                g2o::RobustKernelHuber* rk = new g2o::RobustKernelHuber;
                e->setRobustKernel(rk);
                rk->setDelta(dw.delta);
                AddToGraph(e, ck.pKF, ck.vDpp[i], false, 0, c);
                wKept += e->information()(0,0);
                nKept++;
            }
            ck.vEdge.clear();
            if(wCand > 0.0)
                mInfoDev = std::max(mInfoDev, std::fabs(wKept - wCand) / wCand);
            nCandFree += n;
            nKeptFree += nKept;
            nBudgetFree += K;
            if(nKept > K)
                nOverK++;
            if(mu.diagSubsampleCheck)
            {
                // K and q as the code computes them, from the float settings (review B-2).
                const double eps = (double)mu.depthEdgeSubsampleEps;
                char buf[320];
                snprintf(buf, sizeof(buf), "[UCSLAM] diag subsample kf=%lu n_pass=%d n_kept=%d n_exempt=%d c=%.6f d_sd=%.6f K=%d q=%.9g",
                         ck.pKF->mnId, n, nKept, ck.nExempt, c, UcslamSubsampleShift(ck.vCand, keep), K,
                         mInfoScale / (mInfoScale + eps));
                cout << buf << endl;
            }
        }
        mCands.clear();
    }

    // Diagnostics (UCSLAM.Diag). The caller says whether the next depth edge belongs to a
    // depth-prior map point, and counts the depth-prior points of the window.
    void SetPointIsDpp(bool b) { bDppPoint = b; }
    void CountDppPoint(int nObs) { nDppPoints++; if(nObs <= 1) nDppSingle++; }

    // UCSLAM.DepthGateMode 2, before the gate: every free a_k moves to the median of log z - log z_hat
    // over its depth edges on points that are not depth-prior points, at the initial estimate of the
    // points and poses, when at least 20 such edges exist. A gate at the initial estimate is then
    // centred on the geometry of the window and not on the a_k of the previous local BA. The
    // depth-prior points were placed at that previous a_k and agree with it by construction, so
    // they would otherwise keep a stale a_k in place. Returns how many nodes moved.
    int Recenter()
    {
        std::map<VertexLogScale*, std::vector<double> > r;
        for(size_t i = 0; i < mvDepthEdges.size(); i++)
        {
            if(mvDepthEdgeDpp[i])
                continue;
            EdgeLogDepthBase* e = mvDepthEdges[i];
            VertexLogScale* v = static_cast<VertexLogScale*>(e->vertices()[2]);
            if(v->fixed() || !e->isDepthPositive())
                continue;
            e->computeError();
            r[v].push_back(e->error()(0) + v->estimate());
        }
        int nMoved = 0;
        for(std::map<VertexLogScale*, std::vector<double> >::iterator it = r.begin(); it != r.end(); ++it)
        {
            std::vector<double>& x = it->second;
            if(x.size() < 20)
                continue;
            std::nth_element(x.begin(), x.begin() + x.size() / 2, x.end());
            it->first->setEstimate(x[x.size() / 2]);
            nMoved++;
        }
        nRecentered += nMoved;
        return nMoved;
    }

    // UCSLAM.DepthGateMode 1: the same gate at the initial estimate, before the one solve of the window.
    int PreGate()
    {
        if(mu.depthGateMode == 2)
            Recenter();
        int n = 0;
        for(size_t i = 0; i < mvDepthEdges.size(); i++)
        {
            EdgeLogDepthBase* e = mvDepthEdges[i];
            e->computeError();
            // UC-SLAM (attempt 08): the threshold carries the subsample weight of the edge, 1 without it.
            if(e->chi2() > kChi2Depth * mInfoScale * mvDepthEdgeScale[i] || !e->isDepthPositive())
            {
                e->setLevel(1);
                n++;
            }
            else if(mvDepthEdgeClass[i] == 0)
                nActCand++;
            else if(mvDepthEdgeClass[i] == 1)
                nActExempt++;
            else
                nActFixed++;
        }
        nGated += n;
        return n;
    }

    // Depth edges above the gate, or behind the camera, leave the active set. Returns how many.
    int Gate()
    {
        int n = 0;
        for(size_t i = 0; i < mvDepthEdges.size(); i++)
        {
            EdgeLogDepthBase* e = mvDepthEdges[i];
            if(e->level() != 0)
                continue;
            if(e->chi2() > kChi2Depth * mInfoScale * mvDepthEdgeScale[i] || !e->isDepthPositive())
            {
                e->setLevel(1);
                n++;
            }
        }
        nGated += n;
        return n;
    }

    // Var(a_k) of the window from the inverse of the pose Hessian with the landmarks eliminated,
    // built at the current estimate. Leaves mbMarginalOk false when it cannot be read.
    void ComputeMarginals(UcslamBlockSolverX* pSolver)
    {
        mbMarginalOk = false;
        mCov.resize(0, 0);
        mVarDiag.resize(0);
        if(!pSolver || mOptimizer.indexMapping().empty())
            return;
        mOptimizer.computeActiveErrors();
        pSolver->buildStructure();
        pSolver->buildSystem();
        // UC-SLAM (UCSLAM.LbaMargDiagOnly, attempt 08): only the Var(a_k) the write back reads.
        // UCSLAM.DiagMargCheck also asks the chosen path for the LDLT rcond of its Schur complement.
        double* pRcond = mu.diagMargCheck ? &mMargRcond : static_cast<double*>(NULL);
        if(mu.lbaMargDiagOnly)
            mbMarginalOk = MarginalsDiag(*pSolver, pRcond);
        else
            mbMarginalOk = MarginalsFull(*pSolver, pRcond);
        // UCSLAM.DiagMargCheck: the other path too, and the largest relative difference of Var(a_k) over the
        // free a_k. -1 when both paths fail. Infinite when only one path fails, when only one Var is finite,
        // or when a ratio is not finite while the two Var differ (review, so that std::max never drops a NaN).
        if(mu.diagMargCheck)
        {
            const bool bOther = mu.lbaMargDiagOnly ? MarginalsFull(*pSolver) : MarginalsDiag(*pSolver);
            if(mbMarginalOk != bOther)
                mMargCheck = std::numeric_limits<double>::infinity();
            else if(mbMarginalOk)
            {
                const std::vector<int> cols = FreeScaleColumns((int)mCov.rows());
                mMargCheck = 0.0;
                for(size_t j = 0; j < cols.size(); j++)
                {
                    const double vf = mCov(cols[j], cols[j]), vd = mVarDiag(cols[j]);
                    double d = 0.0;
                    if(std::isfinite(vf) != std::isfinite(vd))
                        d = std::numeric_limits<double>::infinity();
                    else if(std::isfinite(vf) && vd != vf)
                    {
                        d = std::fabs(vd - vf) / std::fabs(vf);
                        if(!std::isfinite(d))
                            d = std::numeric_limits<double>::infinity();
                    }
                    mMargCheck = std::max(mMargCheck, d);
                }
            }
        }
    }

    // The existing path: dense Schur complement, LDLT, inverse of the whole matrix into mCov.
    // pRcond (UCSLAM.DiagMargCheck only) receives the LDLT rcond estimate.
    bool MarginalsFull(UcslamBlockSolverX& solver, double* pRcond = NULL)
    {
        Eigen::MatrixXd S;
        if(!UcslamDensePoseSchur(solver, S))
            return false;
        Eigen::LDLT<Eigen::MatrixXd> ldlt(S);
        if(ldlt.info() != Eigen::Success || !ldlt.isPositive())
            return false;
        if(pRcond)
            *pRcond = ldlt.rcond();
        mCov = ldlt.solve(Eigen::MatrixXd::Identity(S.rows(), S.cols()));
        return true;
    }

    // UC-SLAM (UCSLAM.LbaMargDiagOnly, attempt 08): the lower triangle of the Schur complement, LDLT, and a
    // solve for the columns of the free a_k only, into mVarDiag.
    bool MarginalsDiag(UcslamBlockSolverX& solver, double* pRcond = NULL)
    {
        Eigen::MatrixXd S;
        if(!UcslamDensePoseSchur(solver, S, true))
            return false;
        return UcslamMarginalDiag(S, FreeScaleColumns((int)S.rows()), mVarDiag, pRcond);
    }

    // Columns of the free a_k in the pose Hessian of size n, the entries WriteBack reads.
    std::vector<int> FreeScaleColumns(int n) const
    {
        std::vector<int> cols;
        for(std::map<KeyFrame*,VertexLogScale*>::const_iterator it = mVertices.begin(); it != mVertices.end(); ++it)
        {
            const VertexLogScale* v = it->second;
            if(v->fixed() || v->hessianIndex() < 0)
                continue;
            const int c = v->colInHessian();
            if(c >= 0 && c < n)
                cols.push_back(c);
        }
        return cols;
    }

    void WriteBack()
    {
        const double sigmaRW2 = (double)mu.sigmaRW * (double)mu.sigmaRW;
        std::map<KeyFrame*,double> mS;
        for(size_t i = 0; i < mvDepthEdges.size(); i++)
        {
            EdgeLogDepthBase* e = mvDepthEdges[i];
            if(e->level() != 0 || e->chi2() > kChi2Depth * mInfoScale * mvDepthEdgeScale[i])
                continue;
            mS[mvDepthEdgeKF[i]] += e->information()(0,0);
        }
        for(std::map<KeyFrame*,VertexLogScale*>::iterator it = mVertices.begin(); it != mVertices.end(); ++it)
        {
            KeyFrame* pKF = it->first;
            VertexLogScale* v = it->second;
            if(v->fixed())
                continue;
            double var = -1.0;
            if(mbMarginalOk && v->hessianIndex() >= 0)
            {
                const int c = v->colInHessian();
                if(mu.lbaMargDiagOnly)
                {
                    if(c >= 0 && c < mVarDiag.size())
                        var = mVarDiag(c);
                }
                else if(c >= 0 && c < mCov.rows())
                    var = mCov(c, c);
            }
            if(std::isfinite(var) && var > 0.0)
                nMarginal++;
            else
            {
                double base = mStoredVar[pKF];
                KeyFrame* pPrev = pKF->mPrevKF;
                if(pPrev && mStoredVar.count(pPrev))
                    base = mStoredVar[pPrev] + std::max(sigmaRW2 * std::fabs(pKF->mTimeStamp - pPrev->mTimeStamp), 1e-12);
                const double S = mS.count(pKF) ? mS[pKF] : 0.0;
                var = 1.0 / (1.0 / base + S);
                nFilter++;
            }
            pKF->mLogScale = v->estimate();
            pKF->mLogScaleVar = var;
        }
    }

    // Range of a_k over the optimizable nodes after the write back.
    void RangeA(double& amin, double& amax) const
    {
        amin = 1e30; amax = -1e30;
        for(std::map<KeyFrame*,VertexLogScale*>::const_iterator it = mVertices.begin(); it != mVertices.end(); ++it)
        {
            if(it->second->fixed())
                continue;
            amin = std::min(amin, it->second->estimate());
            amax = std::max(amax, it->second->estimate());
        }
        if(amin > amax)
            amin = amax = 0.0;
    }

    // Extra fields of the lba line under UCSLAM.Diag, vmax is the largest velocity norm of the
    // optimizable keyframes (negative when the BA has none).
    void PrintDiag(const char* type, KeyFrame* pKF, double vmax, int nPoints) const
    {
        double amin, amax;
        RangeA(amin, amax);
        // UC-SLAM (attempt 08): after gated, the depth edges that pass the gate at the initial estimate
        // (DepthGateMode 1 or 2) by class: candidates and kept of the free keyframes (equal without the
        // subsample), exempt, fixed keyframes. info_dev: largest relative deviation of the kept weighted
        // information from the candidate information of a keyframe. marg_check: UCSLAM.DiagMargCheck, -1 when
        // not run. gated_add: edges the gate at add left out, also counted in gated. depth_budget_free: sum of
        // K over the free keyframes (the candidates without the subsample). kept_over_k: free keyframes that
        // kept more than K. marg_rcond: LDLT rcond of the marginals' Schur complement under DiagMargCheck, -1
        // otherwise. One buffer and one write, so that another thread cannot split the line (review).
        char buf[1024];
        snprintf(buf, sizeof(buf),
                 "[UCSLAM] diag lba type=%s kf=%lu t=%.6f a_min=%.4f a_max=%.4f vmax=%.4f points=%d dpp_points=%d dpp_single=%d depth_edges=%d depth_fixed_kf=%d depth_dpp=%d gated=%d"
                 " depth_cand_free=%d depth_kept_free=%d depth_exempt=%d depth_fixed_kept=%d info_dev=%.3e marg_check=%.3e gated_add=%d"
                 " depth_budget_free=%d kept_over_k=%d marg_rcond=%.3e\n",
                 type, pKF->mnId, pKF->mTimeStamp, amin, amax, vmax, nPoints, nDppPoints, nDppSingle,
                 (int)mvDepthEdges.size(), nDepthFixedKF, nDepthDpp, nGated,
                 mbSubsample ? nCandFree : nActCand, mbSubsample ? nKeptFree : nActCand, nActExempt, nActFixed,
                 mInfoDev, mMargCheck, nGatedAtAdd,
                 mbSubsample ? nBudgetFree : nActCand, nOverK, mMargRcond);
        cout << buf << flush;
    }

    void PrintLine(const char* type, KeyFrame* pKF, int nOptKF, int nFixedKF) const
    {
        char buf[512];
        snprintf(buf, sizeof(buf),
                 "[UCSLAM] lba type=%s kf=%lu t=%.6f opt_kfs=%d fixed_kfs=%d depth_edges=%d depth_gated=%d chain=%d prior=%d unary=%d merge=%d detached=%d a_cur=%.6f var_cur=%.4e var_src=%s marginal_kfs=%d filter_kfs=%d",
                 type, pKF->mnId, pKF->mTimeStamp, nOptKF, nFixedKF, (int)mvDepthEdges.size(), nGated, nChain, nPrior,
                 nUnary, nMerge, nDetached, pKF->mLogScale, pKF->mLogScaleVar, mbMarginalOk ? "marginal" : "filter",
                 nMarginal, nFilter);
        if(mu.depthGateMode == 2)
            cout << buf << " recentered=" << nRecentered << endl;
        else
            cout << buf << endl;
    }

    int NumDepthEdges() const { return (int)mvDepthEdges.size(); }

private:
    struct DepthPrior
    {
        bool bQueried, bReady;
        std::vector<float> z, sigma;
        DepthPrior(): bQueried(false), bReady(false) {}
    };

    // UC-SLAM (attempt 08): the subsample candidates of one free keyframe, built but not in the graph yet.
    struct DepthCandKF
    {
        KeyFrame* pKF;
        std::vector<UcslamDepthCand> vCand;
        std::vector<EdgeLogDepthBase*> vEdge;
        std::vector<bool> vDpp;
        int nExempt;                                // exempt edges of the keyframe, for the diag subsample line
        DepthCandKF(): pKF(NULL), nExempt(0) {}
    };

    void AddToGraph(EdgeLogDepthBase* e, KeyFrame* pKF, bool bDpp, bool bFixedKF, char cls, double scale)
    {
        mOptimizer.addEdge(e);
        mvDepthEdges.push_back(e);
        mvDepthEdgeKF.push_back(pKF);
        mvDepthEdgeDpp.push_back(bDpp);
        mvDepthEdgeScale.push_back(scale);
        mvDepthEdgeClass.push_back(cls);
        if(bFixedKF)
            nDepthFixedKF++;
        if(bDpp)
            nDepthDpp++;
    }

    const Settings::Ucslam& mu;
    g2o::SparseOptimizer& mOptimizer;
    const unsigned long mBaseId;
    const double mInfoScale;                        // N_eff / N under ESS deflation, else 1
    std::map<KeyFrame*,VertexLogScale*> mVertices;
    std::map<KeyFrame*,double> mStoredVar;          // stored variance of every node before this BA
    std::map<KeyFrame*,DepthPrior> mDepth;
    std::vector<EdgeLogDepthBase*> mvDepthEdges;
    std::vector<KeyFrame*> mvDepthEdgeKF;
    std::vector<bool> mvDepthEdgeDpp;               // the edge belongs to a depth-prior map point
    int nRecentered;                                // free a_k moved by Recenter (DepthGateMode 2)
    int nChain, nPrior, nUnary, nMerge, nDetached, nGated, nMarginal, nFilter;
    int nDepthFixedKF, nDepthDpp, nDppPoints, nDppSingle;
    bool bDppPoint;
    bool mbMarginalOk;
    Eigen::MatrixXd mCov;
    // UC-SLAM (attempt 08)
    unsigned long mPointId;                         // SetPoint
    int mPointObs;
    bool mbSubsample;                               // UCSLAM.DepthEdgeSubsampleEps acts in this BA
    std::map<unsigned long,DepthCandKF> mCands;     // by keyframe id, so that the flush order is fixed
    std::vector<double> mvDepthEdgeScale;           // subsample weight c_k of the edge, 1 for every other edge
    std::vector<char> mvDepthEdgeClass;             // 0 candidate, 1 exempt, 2 fixed keyframe (AddDepthEdge)
    int nGatedAtAdd, nCandFree, nKeptFree;          // UCSLAM.DepthEdgeGateAtAdd, subsample counts
    int nBudgetFree, nOverK;                        // sum of K over the free keyframes, keyframes that kept more than K
    int nActCand, nActExempt, nActFixed;            // edges that pass PreGate, by class
    double mInfoDev, mMargCheck;                    // diag lba fields info_dev and marg_check
    double mMargRcond;                              // UCSLAM.DiagMargCheck: LDLT rcond of the marginals' Schur complement
    Eigen::VectorXd mVarDiag;                       // UCSLAM.LbaMargDiagOnly: Var(a_k) at the free a_k columns
};

