bool Optimizer::UcslamGeometricLogScale(KeyFrame* pKF, double& a, int& n, int nMin)
{
    a = 0.0;
    n = 0;
    if(!pKF || pKF->isBad())
        return false;
    std::vector<float> vDepth, vSigma;
    if(!pKF->GetDepthPrior(vDepth, vSigma))
        return false;
    const std::vector<MapPoint*> vpMPs = pKF->GetMapPointMatches();
    const Sophus::SE3f Tcw = pKF->GetPose();
    const int nLeft = (pKF->NLeft == -1) ? pKF->N : pKF->NLeft;
    std::vector<double> r;
    r.reserve(nLeft);
    for(int i = 0; i < nLeft && i < (int)vpMPs.size() && i < (int)vDepth.size(); i++)
    {
        MapPoint* pMP = vpMPs[i];
        if(!pMP || pMP->isBad() || pMP->mbFromDepthPrior || !(vDepth[i] > 0.f))
            continue;
        const bool bStereoHere = i < (int)pKF->mvuRight.size() && pKF->mvuRight[i] >= 0.f;
        if(pMP->Observations() < 2 && !bStereoHere)
            continue;
        const float z = (Tcw * pMP->GetWorldPos())(2);
        if(!(z > 0.f))
            continue;
        r.push_back(std::log((double)z) - std::log((double)vDepth[i]));
    }
    n = (int)r.size();
    if(n < nMin || n == 0)
        return false;
    std::nth_element(r.begin(), r.begin() + n / 2, r.end());
    a = r[n / 2];
    return true;
}

double Optimizer::UcslamSeedLogScale(KeyFrame* pKF)
{
    if(!pKF)
        return 0.0;
    if(UcslamParams().logScaleFixed)
        return 0.0;
    if(!UcslamParams().logScaleSeed)
    {
        // The rule of the depth_fix variant.
        if(!(pKF->mLogScaleVar > 0.0) && pKF->mPrevKF && pKF->mPrevKF->mLogScaleVar > 0.0)
            return pKF->mPrevKF->mLogScale;
        return pKF->mLogScale;
    }
    if(pKF->mLogScaleVar > 0.0)
        return pKF->mLogScale;
    double a;
    int n;
    if(UcslamGeometricLogScale(pKF, a, n))
        return a;
    // The random walk prediction from the nearest predecessor that a local BA has estimated.
    KeyFrame* pPrev = pKF->mPrevKF;
    for(int k = 0; pPrev && k < 1000; k++, pPrev = pPrev->mPrevKF)
        if(pPrev->mLogScaleVar > 0.0)
            return pPrev->mLogScale;
    return pKF->mLogScale;
}

bool Optimizer::UcslamHasStereoObservation(MapPoint* pMP)
{
    const map<KeyFrame*,tuple<int,int>> observations = pMP->GetObservations();
    for(map<KeyFrame*,tuple<int,int>>::const_iterator mit = observations.begin(); mit != observations.end(); mit++)
    {
        KeyFrame* pKFi = mit->first;
        if(!pKFi || pKFi->isBad())
            continue;
        if(get<1>(mit->second) != -1)
            return true;
        const int leftIndex = get<0>(mit->second);
        if(leftIndex != -1 && pKFi->NLeft == -1 && leftIndex < (int)pKFi->mvuRight.size() && pKFi->mvuRight[leftIndex] >= 0.f)
            return true;
    }
    return false;
}


